impl fmt::Display for MgmtEv {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            MgmtEv::Unknown(code) => write!(f, "Unknown(0x{:04X})", code),
            _ => write!(f, "{:?}", self),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum MgmtStatus {
    Success = 0x00,
    UnknownCommand = 0x01,
    NotConnected = 0x02,
    Failed = 0x03,
    ConnectFailed = 0x04,
    AuthFailed = 0x05,
    NotPaired = 0x06,
    NoResources = 0x07,
    Timeout = 0x08,
    AlreadyConnected = 0x09,
    Busy = 0x0a,
    Rejected = 0x0b,
    NotSupported = 0x0c,
    InvalidParams = 0x0d,
    Disconnected = 0x0e,
    NotPowered = 0x0f,
    Cancelled = 0x10,
    InvalidIndex = 0x11,
    RFKilled = 0x12,
    AlreadyPaired = 0x13,
    PermissionDenied = 0x14,
    Unknown(u8),
}
impl From<u8> for MgmtStatus {
    fn from(code: u8) -> Self {
        match code {
            0x00 => MgmtStatus::Success,
            0x01 => MgmtStatus::UnknownCommand,
            0x02 => MgmtStatus::NotConnected,
            0x03 => MgmtStatus::Failed,
            0x04 => MgmtStatus::ConnectFailed,
            0x05 => MgmtStatus::AuthFailed,
            0x06 => MgmtStatus::NotPaired,
            0x07 => MgmtStatus::NoResources,
            0x08 => MgmtStatus::Timeout,
            0x09 => MgmtStatus::AlreadyConnected,
            0x0a => MgmtStatus::Busy,
            0x0b => MgmtStatus::Rejected,
            0x0c => MgmtStatus::NotSupported,
            0x0d => MgmtStatus::InvalidParams,
            0x0e => MgmtStatus::Disconnected,
            0x0f => MgmtStatus::NotPowered,
            0x10 => MgmtStatus::Cancelled,
            0x11 => MgmtStatus::InvalidIndex,
            0x12 => MgmtStatus::RFKilled,
            0x13 => MgmtStatus::AlreadyPaired,
            0x14 => MgmtStatus::PermissionDenied,
            other => MgmtStatus::Unknown(other),
        }
    }
}

impl std::fmt::Display for MgmtStatus {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let desc = match self {
            MgmtStatus::Success => "Success",
            MgmtStatus::UnknownCommand => "Unknown command",
            MgmtStatus::NotConnected => "Not connected",
            MgmtStatus::Failed => "Failed",
            MgmtStatus::ConnectFailed => "Connect failed",
            MgmtStatus::AuthFailed => "Authentication failed",
            MgmtStatus::NotPaired => "Not paired",
            MgmtStatus::NoResources => "No resources",
            MgmtStatus::Timeout => "Timeout",
            MgmtStatus::AlreadyConnected => "Already connected",
            MgmtStatus::Busy => "Busy",
            MgmtStatus::Rejected => "Rejected",
            MgmtStatus::NotSupported => "Not supported",
            MgmtStatus::InvalidParams => "Invalid parameters",
            MgmtStatus::Disconnected => "Disconnected",
            MgmtStatus::NotPowered => "Not powered",
            MgmtStatus::Cancelled => "Cancelled",
            MgmtStatus::InvalidIndex => "Invalid index",
            MgmtStatus::RFKilled => "RFKILLED (blocked by rfkill)",
            MgmtStatus::AlreadyPaired => "Already paired",
            MgmtStatus::PermissionDenied => "Permission denied",
            MgmtStatus::Unknown(code) => return write!(f, "Unknown (0x{:02x})", code),
        };
        write!(f, "{}", desc)
    }
}

